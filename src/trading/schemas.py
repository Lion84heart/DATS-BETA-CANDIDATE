# A/B Testing
# ---------------------------------------------------------------------------


class ABTest(BaseModel):
    """Configuration for an A/B test between two strategies."""

    name: str = Field(..., description="Test name / identifier.")
    strategy_a_name: str = Field(..., description="Name of strategy A.")
    strategy_b_name: str = Field(..., description="Name of strategy B.")
    confidence_level: float = Field(
        default=0.95, ge=0.0, le=1.0, description="Statistical confidence level."
    )
    status: Literal["pending", "running", "completed"] = Field(
        default="pending", description="Test status."
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Test creation timestamp.",
    )

    @field_validator("created_at", mode="before")
    @classmethod
    def _ensure_utc(cls, value: datetime | str) -> datetime:
        if isinstance(value, str):
            value = datetime.fromisoformat(value.replace("Z", "+00:00"))
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        return value


class ABTestResult(BaseModel):
    """Result of an A/B test between two strategies."""

    test_name: str = Field(..., description="Test name / identifier.")
    strategy_a_name: str = Field(..., description="Name of strategy A.")
    strategy_b_name: str = Field(..., description="Name of strategy B.")
    strategy_a_metrics: PerformanceMetrics = Field(
        ..., description="Performance metrics for strategy A."
    )
    strategy_b_metrics: PerformanceMetrics = Field(
        ..., description="Performance metrics for strategy B."
    )
    winner: Literal["A", "B", "tie"] = Field(
        ..., description="Winning strategy or tie."
    )
    p_value: float = Field(
        ..., ge=0.0, le=1.0, description="Statistical significance p-value."
    )
    confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Confidence level used."
    )
    recommendation: str = Field(
        default="", description="Human-readable recommendation."
    )


